#!/usr/bin/env python3
"""Publish reproducible LCOV HTML reports as a static GitHub Pages site.

Copies generated HTML rather than changing the LCOV report; relative links to
images, styles and CFG pages continue to work under a GitHub Pages subpath.
"""

import argparse
import html
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PROJECTS = ("cjson", "inih")
VARIANTS = ("original", "compatible", "extended")
LICENSES = {"cjson": "LICENSE", "inih": "LICENSE.txt"}


def validate_reports(root):
    for project in PROJECTS:
        base = root / "build" / project
        report = base / "bb_coverage.json"
        if not report.is_file():
            raise FileNotFoundError(f"Run bash scripts/demo.sh first: missing {report}")
        for variant in VARIANTS:
            index = base / f"html-{variant}" / "index.html"
            if not index.is_file():
                raise FileNotFoundError(f"Run bash scripts/demo.sh first: missing {index}")
        cmds = [
            [sys.executable, "tools/compare_compat.py",
             str(base / "html-original"), str(base / "html-compatible")],
            [sys.executable, "tools/verify_extended.py", "--report", str(report),
             "--html", str(base / "html-extended")],
            [sys.executable, "tools/verify_instrumentation.py", "--report", str(report),
             "--strict-mapping"],
        ]
        for cmd in cmds:
            subprocess.run(cmd, cwd=root, check=True)


def report_summary(root):
    result = {}
    for project in PROJECTS:
        path = root / "build" / project / "bb_coverage.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        stats = data["summary"]
        covered, total = stats["covered"], stats["total"]
        if not isinstance(covered, int) or not isinstance(total, int) or not (0 <= covered <= total):
            raise ValueError(f"Invalid coverage data: {path}")
        result[project] = {"covered": covered, "total": total,
                           "percent": 100 * covered / total if total else 0.,
                           "runs": data["runs"]}
    return result


def site_index(summaries):
    rows = []
    for project in PROJECTS:
        s = summaries[project]
        name = "cJSON" if project == "cjson" else "inih"
        links = " | ".join(
            f'<a href="reports/{project}/{kind}/index.html">{label}</a>'
            for kind, label in (("original", "Original genhtml"),
                                ("compatible", "Compatible mode"),
                                ("extended", "BB extended"))
        )
        rows.append(f'<tr><th scope="row">{html.escape(name)}</th>'
                    f'<td>{s["covered"]} / {s["total"]} ({s["percent"]:.1f}%)</td>'
                    f'<td>{s["runs"]}</td><td>{links}<br><small><a href="reports/{project}/UPSTREAM-LICENSE.txt">Upstream license</a></small></td></tr>')
    content = "\n".join(rows)
    return f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>LCOV Basic Block Coverage — test reports</title>
<style>
body{{font:15px/1.55 system-ui,-apple-system,sans-serif;max-width:980px;margin:50px auto;padding:0 20px;color:#222}}
h1{{line-height:1.2}} table{{width:100%;border-collapse:collapse;margin:25px 0}}
th,td{{padding:11px;border-bottom:1px solid #ddd;text-align:left;vertical-align:top}}
small,.note{{color:#555}} a{{color:#1756a9}}
@media(max-width:680px){{table{{font-size:12px}}th,td{{padding:7px}}}}
</style></head><body>
<h1>LCOV Basic Block Coverage</h1>
<p>Reproducible static coverage reports from Clang/LLVM SanitizerCoverage,
including source-line BB markers and per-function control-flow graphs.</p>
<table><thead><tr><th>Project</th><th>BB coverage</th><th>Test runs</th><th>HTML reports</th></tr></thead>
<tbody>{content}</tbody></table>
<p><b>Report types:</b> Original is generated by the system genhtml; Compatible
is generated by the modified genhtml without <code>--bb-report</code>;
BB extended adds Basic Block Coverage. The first two have matching coverage data.</p>
<p class="note">Coverage describes the supplied test drivers, not the upstream
projects' complete test suites. A gray CFG node represents unknown attribution,
not necessarily an unexecuted block. CFG edges describe possible paths.</p>
<p><small>Source code, reproducibility instructions, and test methodology are available
in the corresponding GitHub repository. Pages are an export of the generated
reports, not an independent build.</small></p>
</body></html>\n'''


def publish(root):
    """Create one complete static site from previously generated reports."""
    summaries = report_summary(root)
    docs = root / "docs"
    docs.mkdir(exist_ok=True)
    # Build off to the side: interrupted copies do not replace the published tree.
    with tempfile.TemporaryDirectory(prefix="bb-pages-", dir=root) as temp:
        staged = Path(temp)
        for project in PROJECTS:
            for kind in VARIANTS:
                source = root / "build" / project / f"html-{kind}"
                if not (source / "index.html").is_file():
                    raise FileNotFoundError(f"Missing HTML report: {source}")
                target = staged / "reports" / project / kind
                shutil.copytree(source, target)
        # Generated reports contain upstream source code; retain its license notices.
        for project, license_name in LICENSES.items():
            source_license = root / "third_party" / ("cJSON" if project == "cjson" else "inih") / license_name
            if not source_license.is_file():
                raise FileNotFoundError(f"Missing upstream license: {source_license}. Run demo.sh first")
            dst = staged / "reports" / project / "UPSTREAM-LICENSE.txt"
            shutil.copy2(source_license, dst)
        (staged / "index.html").write_text(site_index(summaries), encoding="utf-8")
        target = docs / "reports"
        if target.exists():
            shutil.rmtree(target)
        shutil.move(str(staged / "reports"), str(target))
        shutil.copyfile(staged / "index.html", docs / "index.html")
        (docs / ".nojekyll").touch()
    n_pages = len(list((docs / "reports").rglob("*.html")))
    bytes_total = sum(p.stat().st_size for p in (docs / "reports").rglob("*") if p.is_file())
    print(f"Published {n_pages} HTML pages to docs/reports/ ({bytes_total/1024/1024:.2f} MiB)")
    print("Landing page: docs/index.html")
    for project in PROJECTS:
        s = summaries[project]
        print(f"  {project}: {s['covered']}/{s['total']} BB ({s['percent']:.1f}%), "
              "original / compatible / extended")
    return n_pages


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1],
                        help="Project root (defaults to this script's repository)")
    parser.add_argument("--skip-validation", action="store_true",
                        help="Skip verification; for local debugging only")
    args = parser.parse_args()
    root = args.root.resolve()
    if not args.skip_validation:
        validate_reports(root)
    publish(root)


if __name__ == "__main__":
    main()
